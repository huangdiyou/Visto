const dictionaries: Record<AppLocale, Record<MessageKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export type Translator = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

export function normalizeLocale(locale: string | null | undefined): AppLocale {
  const value = locale?.toLowerCase() ?? "";
  if (value.startsWith("en")) return "en-US";
  return "zh-CN";
}

export function createTranslator(
  locale: string | null | undefined,
): Translator {
  const normalized = normalizeLocale(locale);
  const messages = dictionaries[normalized];
  return (key, values) => interpolate(messages[key] ?? zhCN[key], values);
}

export function localeLabel(
  locale: string | null | undefined,
  displayLocale: string | null | undefined = locale,
): string {
  const normalized = normalizeLocale(locale);
  const display = normalizeLocale(displayLocale);
  if (display === "zh-CN") {
    return normalized === "zh-CN" ? "简体中文" : "English";
  }
  return normalized === "zh-CN" ? "Simplified Chinese" : "English";
}

export function formatDate(
  value: string | Date,
  locale: string | null | undefined,
  options: Intl.DateTimeFormatOptions,
) {
  return new Intl.DateTimeFormat(normalizeLocale(locale), options).format(
    new Date(value),
  );
}

export function formatRelativeDate(
  value: string,
  locale: string | null | undefined,
  t: Translator = createTranslator(locale),
) {
  const timestamp = new Date(value).getTime();
  const difference = Date.now() - timestamp;
  const day = 24 * 60 * 60 * 1000;
  if (difference >= 0 && difference < day) return t("common.today");
  if (difference >= day && difference < day * 2) return t("common.yesterday");
  return formatDate(value, locale, {
    month: "numeric",
    day: "numeric",
  });
}

function interpolate(
  message: string,
  values: Record<string, string | number> | undefined,
) {
  if (!values) return message;
  return message.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key)
      ? String(values[key])
      : match,
  );
}
